using Common;

// ─────────────────────────────────────────────────────────────────────────────
// ПРИКЛАД 10. Повний CRUD на контролерах
//
// Класичний набір операцій над ресурсом «товар»: список, читання, створення,
// повна заміна, видалення — з правильними кодами відповідей і заголовком Location.
// (Валідацію вводу навмисно майже не робимо — це тема прикладу 11.)
// ─────────────────────────────────────────────────────────────────────────────

var builder = WebApplication.CreateBuilder(args);

// ======================================================================
//  1 · СЕРВІСИ
// ======================================================================
builder.Services.AddCatalog();
builder.Services.AddControllers();   // інфраструктура MVC: активація, binding, форматери
builder.Services.AddApiDocs();

var app = builder.Build();

// ======================================================================
//  2 · КОНВЕЄР
// ======================================================================
app.MapApiDocs();

// ======================================================================
//  3 · ЗАПИТИ
// ======================================================================
// Обробники — у ProductsController / CategoriesController (тека Controllers/).
app.MapGet("/", () => Results.Redirect("/products"));
app.MapControllers();

app.Run();
