using Common;

// ─────────────────────────────────────────────────────────────────────────────
// ПРИКЛАД 12. MVC-контролери для Web API
//
// Альтернатива Minimal API: контролери-класи. Доречні, коли багато споріднених
// endpoint-ів, потрібні фільтри, конвенції, успадкування.
// Той самий конвеєр, той самий DI — інша «форма» оголошення endpoint-ів.
// ─────────────────────────────────────────────────────────────────────────────

var builder = WebApplication.CreateBuilder(args);

// ======================================================================
//  1 · СЕРВІСИ
// ======================================================================
builder.Services.AddCatalog();
builder.Services.AddControllers();   // інфраструктура MVC: активація, binding, форматери
builder.Services.AddApiDocs();

var app = builder.Build();

// ======================================================================
//  2 · КОНВЕЄР
// ======================================================================
app.MapApiDocs();

// ======================================================================
//  3 · ЗАПИТИ
// ======================================================================
// Самі обробники — у класах-контролерах (тека Controllers/).
app.MapGet("/", () => Results.Redirect("/api/products"));
app.MapControllers();   // додає дії контролерів до таблиці маршрутів

app.Run();
